export const shopDicts: Record<ShopLocale, ShopDict> = { bn: bnDict, en: enDict };

/** Dictionary for a payload locale; anything unknown falls back to bn. */
export function shopT(locale: unknown): ShopDict {
  return locale === "en" ? shopDicts.en : shopDicts.bn;
}

/** Normalize a payload locale value to a ShopLocale (default bn). */
export function shopLocaleOf(locale: unknown): ShopLocale {
  return locale === "en" ? "en" : "bn";
}
