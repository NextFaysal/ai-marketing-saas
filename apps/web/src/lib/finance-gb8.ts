const MISC_DICTS = { bn: miscBn, en: miscEn };
/** MB2 (ML6): label helpers read the `misc` namespace directly and
 * take an optional locale (default "bn" — existing callers and
 * tests keep the Bengali output they have today). The catalog
 * arrays below keep bn `label`/`description` and gain parallel
 * `labelEn`/`descriptionEn` companions (D7-style additive fields)
 * plus *For(locale) pickers. */
function L(locale: UiLocale | undefined, key: string): string {
  return tr(MISC_DICTS, locale ?? "bn", key) ?? key;
}

