export const adminDicts: Record<UiLocale, AdminDict> = { bn, en };

export function getAdminDict(locale: UiLocale | string | null | undefined): AdminDict {
  return locale === "en" ? adminDicts.en : adminDicts.bn;
}

/** Stored preference (`admin_ui_locale`) → platform default bn. Same
 *  resolution as the switcher; used by module-level helpers and pages
 *  without a React tree (e.g. not-found / dialog helpers). */
export function resolveAdminLocale(): UiLocale {
  if (typeof window === "undefined") return "bn";
  try {
    return window.localStorage.getItem(ADMIN_LOCALE_STORAGE_KEY) === "en" ? "en" : "bn";
  } catch {
    return "bn";
  }
}

/** `{name}` → params[name]; unknown placeholders stay literal. Same
 *  semantics as the web dictionary lookup helper. */
export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name as keyof typeof params]) : whole,
  );
}

/** Sorted unique `{name}` placeholders of a template (parity tests). */
export function placeholdersOf(template: string): string[] {
  const out = new Set<string>();
  let m: RegExpExecArray | null;
  const re = /\{(\w+)\}/g;
  while ((m = re.exec(template)) !== null) out.add(m[1]!);
  return [...out].sort();
}

function lookupPath(dict: AdminDict, path: string): unknown {
  let cur: unknown = dict;
  for (const part of path.split(".")) {
    if (cur && typeof cur === "object" && part in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[part];
    } else return undefined;
  }
  return cur;
}

const warned = new Set<string>();

/** Path lookup against the active locale's dictionary with bn fallback
 *  for a whole missing string (parity makes that practically impossible)
 *  and interpolation. Mirrors the web `tr()` contract. */
export function trAdmin(
  locale: UiLocale,
  path: string,
  params?: Record<string, string | number>,
): string {
  let value = lookupPath(adminDicts[locale], path);
  if (typeof value !== "string") {
    value = lookupPath(adminDicts.bn, path);
  }
  if (typeof value !== "string") {
    if (!warned.has(path)) {
      warned.add(path);
      console.warn(`[i18n] missing admin key: ${path}`);
    }
    return path;
  }
  return interpolate(value, params);
}

/** Count with the locale's plural/classifier shape, mirroring the web
 *  helper: bn → digits + suffix ("১২টি"), en → "1 item" / "3 items". */
export function countWithClassifier(
  locale: UiLocale,
  count: number,
  opts: { bnSuffix: string; enOne: string; enOther: string; formattedCount?: string },
): string {
  const n = opts.formattedCount ?? String(count);
  if (locale === "bn") return opts.bnSuffix ? `${n}${opts.bnSuffix}` : n;
  return `${n} ${count === 1 ? opts.enOne : opts.enOther}`;
}
