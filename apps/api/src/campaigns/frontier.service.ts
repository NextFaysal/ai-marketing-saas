  /** Pause / resume / end. Existing instance drafts are
   * NEVER touched — only future generation stops (pause,
   * end) or resumes (resume). Ended is terminal. */
  async seriesAction(organizationId: string, actorId: string, seriesId: string, action: string) {
    const p = this.prisma as any;
    const row = await p.campaignPlanSeries?.findFirst({ where: { id: seriesId, organizationId } }).catch(() => null);
    if (!row) throw new NotFoundException("Series not found in this organization");
    let status: string | null = null;
    if (action === "pause") {
      if (row.status === "ended") throw new BadRequestException("An ended series cannot be paused");
      status = "paused";
    } else if (action === "resume") {
      if (row.status === "ended") throw new BadRequestException("An ended series cannot be resumed — create a new series instead");
      status = "active";
    } else if (action === "end") {
      status = "ended";
    } else {
      throw new BadRequestException(`action must be pause, resume or end (got "${action}")`);
    }
    const updated = await p.campaignPlanSeries.update({ where: { id: row.id }, data: { status } });
    await this.audit.log({ organizationId, userId: actorId, action: `campaign.series_${action}`, entityType: "CampaignPlanSeries", entityId: row.id, metadata: { from: row.status, to: status } }).catch(() => undefined);
    return this.seriesView(updated);
  }

  /** The generation sweep. Per active series, per tick, at
   * most ONE instance is generated: occurrence nextIndex,
   * once now reaches (date − leadDays). The one-pending-
   * instance rule: while the previously generated instance
   * still sits in "draft", generation HOLDS — the sweep
   * never piles drafts up. Once that instance moves into
   * the approval flow (or is deleted), the next occurrence
   * generates. Failures are isolated per series and land
   * in the audit log; the sweep itself never throws. */
  async scanCampaignSeries(now = new Date()) {
    const p = this.prisma as any;
    if (!p.campaignPlanSeries?.findMany) return { generated: 0, held: 0, ended: 0, failed: 0, skipped: 0 };
    const rows = await p.campaignPlanSeries.findMany({ where: { status: "active" }, take: 50 }).catch(() => []);
    let generated = 0; let held = 0; let ended = 0; let failed = 0; let skipped = 0;
    for (const row of rows as any[]) {
      try {
        const nextDate = seriesOccurrenceDate(row, row.nextIndex);
        if (!nextDate) {
          await p.campaignPlanSeries.update({ where: { id: row.id }, data: { status: "ended" } });
          await this.audit.log({ organizationId: row.organizationId, userId: row.createdById, action: "campaign.series_ended", entityType: "CampaignPlanSeries", entityId: row.id, metadata: { reason: "occurrences_exhausted" } }).catch(() => undefined);
          ended++;
          continue;
        }
        if (now.getTime() < nextDate.getTime() - Number(row.leadDays ?? 3) * DAY_MS) { skipped++; continue; }
        if (row.pendingPlanId) {
          const pending = await p.campaignPlan.findFirst({ where: { id: row.pendingPlanId, organizationId: row.organizationId } }).catch(() => null);
          if (pending && pending.status === "draft") { held++; continue; }
          await p.campaignPlanSeries.update({ where: { id: row.id }, data: { pendingPlanId: null } });
        }
        const dateLabel = nextDate.toISOString().slice(0, 10);
        const clone: any = await this.campaigns.duplicatePlan(row.organizationId, row.createdById, row.sourcePlanId, {
          name: `${row.name} — ${dateLabel}`,
        });
        await p.campaignPlan.update({ where: { id: clone.id }, data: { seriesId: row.id, seriesInstanceDate: nextDate } });
        await p.campaignPlanSeries.update({
          where: { id: row.id },
          data: { pendingPlanId: clone.id, nextIndex: row.nextIndex + 1, lastGeneratedAt: now },
        });
        await this.audit.log({ organizationId: row.organizationId, userId: row.createdById, action: "campaign.series_instance_created", entityType: "CampaignPlan", entityId: clone.id, metadata: { seriesId: row.id, instanceDate: nextDate.toISOString() } }).catch(() => undefined);
        generated++;
      } catch (e) {
        failed++;
        await this.audit.log({ organizationId: row.organizationId, userId: row.createdById, action: "campaign.series_generation_failed", entityType: "CampaignPlanSeries", entityId: row.id, metadata: { error: e instanceof Error ? e.message.slice(0, 200) : "error" } }).catch(() => undefined);
      }
    }
    return { generated, held, ended, failed, skipped };
  }
